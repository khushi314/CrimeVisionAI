"""
Forensic PDF Report Generator (Milestone 6 Activity 6.3).
Uses ReportLab when installed, with a standards-compliant pure-Python PDF 1.4
fallback so automated tests and lightweight environments always produce valid PDFs.
"""

import time
from pathlib import Path
from typing import Dict, Any, List, Optional

try:
    from backend.config import REPORTS_DIR
except ImportError:
    from config import REPORTS_DIR


def generate_forensic_pdf(session_id: str, data: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """Compile structured forensic session data into a downloadable PDF report."""
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    target = Path(output_path) if output_path else REPORTS_DIR / f"forensic_report_{session_id[:12]}.pdf"

    lines = _build_report_lines(session_id, data)

    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer

        doc = SimpleDocTemplate(str(target), pagesize=letter, title=f"CrimeVision AI Report {session_id}")
        styles = getSampleStyleSheet()
        story = [
            Paragraph("<b>CrimeVision AI — Multimodal Forensic Analysis Report</b>", styles["Title"]),
            Spacer(1, 12),
        ]
        for line in lines:
            safe = (
                line.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
            )
            if line.startswith("## "):
                story.append(Spacer(1, 8))
                story.append(Paragraph(f"<b>{safe[3:]}</b>", styles["Heading2"]))
            else:
                story.append(Paragraph(safe, styles["BodyText"]))
                story.append(Spacer(1, 4))
        doc.build(story)
        return target
    except ImportError:
        _write_minimal_pdf(target, lines)
        return target


def _build_report_lines(session_id: str, data: Dict[str, Any]) -> List[str]:
    timestamp_str = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime())
    mode = str(data.get("mode", "multimodal")).upper()
    lines: List[str] = [
        f"Case Session ID: {session_id}",
        f"Generated At: {timestamp_str}",
        f"Analysis Mode: {mode}",
        "## Executive Summary",
    ]

    if data.get("ai_scene_summary"):
        s = data["ai_scene_summary"]
        lines.append(f"Summary Type: {s.get('summary_type', 'N/A')}")
        lines.append(f"Description: {s.get('brief_description', 'N/A')}")
    if data.get("visual_summary"):
        lines.append(f"Visual Summary: {data['visual_summary']}")
    if data.get("ai_summary"):
        lines.append(f"Audio Intelligence Summary: {data['ai_summary']}")

    counts = data.get("counts")
    if counts:
        lines.append("## Quantitative Detections")
        lines.append(
            f"Objects: {counts.get('objects', 0)} | Persons: {counts.get('persons', 0)} | "
            f"Weapons: {counts.get('weapons', 0)} | Location: {data.get('location', 'N/A')}"
        )

    facts = data.get("evidence_facts") or data.get("scene_intelligence", {}).get("objects_detected")
    if facts:
        lines.append("## Cataloged Evidence Items")
        lines.append(", ".join(str(f) for f in facts))

    scenarios = data.get("scenarios") or []
    if scenarios:
        lines.append("## Investigative Scenario Hypotheses")
        for sc in scenarios:
            if isinstance(sc, dict):
                lines.append(f"- {sc.get('title', 'Scenario')}: {sc.get('description', '')}")
            else:
                lines.append(f"- {sc}")

    timeline = data.get("timeline") or data.get("unified_timeline") or []
    if timeline:
        lines.append("## Chronological Forensic Timeline")
        for item in timeline[:25]:
            cert = f" [Certainty: {item['certainty']}]" if item.get("certainty") else ""
            lines.append(f"[{item.get('time', '00:00')}] {item.get('event', '')}{cert}")

    consistency = data.get("consistency")
    if consistency:
        lines.append("## Cross-Modal Consistency Audit")
        lines.append(f"Consistency Score: {consistency.get('overall_score', 0.0)}")
        for match in consistency.get("matches", []):
            lines.append(f"Match: {match}")
        for conflict in consistency.get("conflicts", []):
            lines.append(f"Discrepancy: {conflict}")

    lines.append("## Ethical & Evidentiary Disclaimer")
    lines.append(
        "This report is generated by automated computer vision and speech analysis pipelines "
        "for investigative triage only. Outputs do not constitute proof of identity or criminal liability."
    )
    return lines


def _write_minimal_pdf(target: Path, lines: List[str]) -> None:
    """Write a valid single-page PDF 1.4 file using only the Python standard library."""
    def esc(text: str) -> str:
        ascii_safe = text.encode("latin-1", errors="replace").decode("latin-1")
        return ascii_safe.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    stream_cmds = ["BT", "/F1 13 Tf", "50 750 Td", "(CrimeVision AI - Forensic Investigation Report) Tj", "/F1 9 Tf"]
    y_step = -14
    for raw_line in lines[:44]:
        clipped = raw_line[:96]
        stream_cmds.append(f"0 {y_step} Td ({esc(clipped)}) Tj")
    stream_cmds.append("ET")
    stream_bytes = "\n".join(stream_cmds).encode("latin-1")

    objects = [
        b"1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n",
        b"2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n",
        b"3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >> endobj\n",
        b"4 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n",
        f"5 0 obj << /Length {len(stream_bytes)} >> stream\n".encode("latin-1") + stream_bytes + b"\nendstream endobj\n",
    ]

    pdf = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for obj in objects:
        offsets.append(len(pdf))
        pdf.extend(obj)

    xref_pos = len(pdf)
    pdf.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode("latin-1"))
    for off in offsets[1:]:
        pdf.extend(f"{off:010d} 00000 n \n".encode("latin-1"))
    pdf.extend(
        f"trailer << /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode("latin-1")
    )
    target.write_bytes(bytes(pdf))
